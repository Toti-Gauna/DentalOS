import { test } from '@playwright/test'
import { fresh, jump, setRole } from './helpers'

// Genera las capturas citadas en docs/tableflow/checkpoint.md (viewport y estado en el nombre).
const OUT = 'docs/tableflow/screens'
test('capturas de ambas experiencias y del admin', async ({ page }) => {
  test.skip(!process.env.CAPTURE, 'Solo con CAPTURE=1 (npm run screens)')
  await page.setViewportSize({ width: 1280, height: 900 })
  await fresh(page, '/#/')
  await page.screenshot({ path: `${OUT}/01-landing-1280x900-seed-servicio.png` })
  await page.goto('/#/mesa-clara/carta')
  await page.screenshot({ path: `${OUT}/02-mesa-clara-carta-1280x900-lun19-10h.png` })
  await jump(page, 'Ir a las 12:00 (almuerzo)')
  await page.getByTestId('open-MC-12').click()
  await page.getByLabel('Papas fritas').check()
  await page.screenshot({ path: `${OUT}/03-mesa-clara-detalle-1280x900-lun19-12h.png` })
  await page.keyboard.press('Escape')
  await page.goto('/#/mesa-clara/reservar')
  await page.screenshot({ path: `${OUT}/04-mesa-clara-reservar-1280x900.png` })
  await page.goto('/#/mesa-clara/simulador')
  await page.getByTestId('chat-input').fill('Mesa para 4 el lunes a las 20')
  await page.getByTestId('chat-send').click()
  await page.screenshot({ path: `${OUT}/05-mesa-clara-simulador-1280x900.png` })
  await setRole(page, /Recepción/)
  await page.screenshot({ path: `${OUT}/06-admin-reservas-1280x900.png` })
  await page.goto('/#/admin/salon')
  await page.screenshot({ path: `${OUT}/07-admin-salon-1280x900.png` })
  await setRole(page, /Encargado/)
  await page.getByTestId('biz-select').selectOption('ritual-cafe')
  await page.goto('/#/admin/cocina')
  await page.screenshot({ path: `${OUT}/08-admin-cocina-cafe-1280x900.png` })
  await page.goto('/#/admin/resumen')
  await page.screenshot({ path: `${OUT}/09-admin-resumen-cafe-1280x900.png` })
  await page.goto('/#/admin/caja')
  await page.screenshot({ path: `${OUT}/10-admin-caja-cafe-1280x900.png` })
  await page.goto('/#/admin/automatizaciones')
  await page.screenshot({ path: `${OUT}/11-admin-automatizaciones-1280x900.png` })
  await setRole(page, /invitado/)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/ritual-cafe/carta')
  await page.screenshot({ path: `${OUT}/12-ritual-cafe-carta-390x844.png` })
  await page.getByTestId('open-RC-04').click()
  await page.getByLabel('Mediano').check()
  await page.getByLabel('Entera').check()
  await page.screenshot({ path: `${OUT}/13-ritual-cafe-detalle-390x844.png` })
  await page.getByTestId('add-to-cart').click()
  await page.screenshot({ path: `${OUT}/14-ritual-cafe-carrito-fijo-390x844.png` })
  await page.setViewportSize({ width: 320, height: 640 })
  await page.goto('/#/ritual-cafe/pedido')
  await page.screenshot({ path: `${OUT}/15-ritual-cafe-pedido-320x640.png` })
})
