import { test, expect } from '@playwright/test'
import { fresh, jump, setRole, state } from './helpers'

test('S07/S08 por la UI: agotado y precio cambiado desde admin bloquean el envío', async ({ page }) => {
  await fresh(page, '/#/mesa-clara/carta')
  await jump(page, 'Ir a las 12:00 (almuerzo)')
  await page.getByTestId('open-MC-01').click()
  await page.getByTestId('add-to-cart').click()
  await page.getByRole('link', { name: /Mi pedido/ }).first().click()
  await page.getByTestId('mesa-select').selectOption('T-MC-02')
  // precio cambia en admin (encargado)
  await setRole(page, /Encargado/)
  await page.goto('/#/admin/carta')
  await page.getByTestId('edit-MC-01').click()
  await page.getByTestId('edit-price').fill('14000')
  await page.getByTestId('dialog-confirm').click()
  await setRole(page, /invitado/)
  await page.goto('/#/mesa-clara/pedido')
  await page.getByTestId('send-order').click()
  await expect(page.getByTestId('order-error')).toContainText('El precio cambió')
  await expect(page.getByTestId('order-error')).toContainText('$ 14.000,00')
  expect((await state(page)).orders).toHaveLength(12)
  await page.getByTestId('ack-prices').click()
  // ahora lo agotan
  await setRole(page, /Encargado/)
  await page.goto('/#/admin/carta')
  await page.getByTestId('toggle-MC-01').click()
  await setRole(page, /invitado/)
  await page.goto('/#/mesa-clara/pedido')
  await page.getByTestId('send-order').click()
  await expect(page.getByTestId('order-error')).toContainText('Este plato se agotó')
  expect((await state(page)).orders).toHaveLength(12)
})

