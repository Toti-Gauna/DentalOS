test('M12 por la UI: reintentar una automatización fallida reutiliza la misma ejecución', async ({ page }) => {
  await fresh(page, '/#/admin/automatizaciones')
  await setRole(page, /Encargado/)
  await page.goto('/#/admin/automatizaciones')
  await expect(page.getByTestId('runs-pending')).toHaveText('1')
  await page.getByTestId('retry-RUN-0010').click()
  await expect(page.getByTestId('run-RUN-0010')).toContainText('recuperada')
  await expect(page.getByTestId('runs-pending')).toHaveText('0')
  const s = await state(page)
  expect(s.messages.filter((m: any) => m.messageKey === s.runs.find((r: any) => r.id === 'RUN-0010').key)).toHaveLength(1)
  await page.getByTestId('preview-campaign').click()
  await expect(page.getByTestId('campaign-result')).toContainText('Omitidos')
  expect(s.messages.length).toBe((await state(page)).messages.length) // ningún mensaje saliente
})

